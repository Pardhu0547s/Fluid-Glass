#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION="$(<"$ROOT/VERSION")"
DIST="$ROOT/dist/fluid-glass-$VERSION"
python3 "$ROOT/scripts/generate-tokens.py"
rm -rf -- "$DIST"
mkdir -p "$DIST/extension" "$DIST/themes/Fluid-Glass-Dark" "$DIST/themes/Fluid-Glass-Light"
cp -a "$ROOT/src/gnome-shell/." "$DIST/extension/"
cp -a "$ROOT/src/gtk3/dark/." "$DIST/themes/Fluid-Glass-Dark/"
cp -a "$ROOT/src/gtk3/light/." "$DIST/themes/Fluid-Glass-Light/"
mkdir -p "$DIST/themes/Fluid-Glass-Dark/gtk-4.0" "$DIST/themes/Fluid-Glass-Light/gtk-4.0"
cp -a "$ROOT/src/gtk4/dark/gtk-4.0/." "$DIST/themes/Fluid-Glass-Dark/gtk-4.0/"
cp -a "$ROOT/src/gtk4/light/gtk-4.0/." "$DIST/themes/Fluid-Glass-Light/gtk-4.0/"
cp "$ROOT/VERSION" "$DIST/VERSION"; cp "$ROOT/LICENSE" "$DIST/LICENSE"
python3 "$ROOT/scripts/package.py" "$DIST"
printf 'Built Fluid Glass %s at %s\n' "$VERSION" "$DIST"
