#!/usr/bin/env bash
#
# Fluid Glass for Linux build script
#
# Compiles the vendored MacTahoe SCSS (exact MacTahoe geometry) together with
# the Fluid Glass material overlay into ready-to-install themes in ./dist.
#
# Usage: ./build.sh [OPTIONS]
#   -c, --color   dark|light|all          Color variants      (default: all)
#   -s, --style   clear|normal|frosted    Glass strength      (default: normal)
#   -n, --name    NAME                    Theme base name     (default: Fluid-Glass)
#   -o, --out     DIR                     Output directory    (default: ./dist)
#       --mac27, --hd                     macOS 27" Desktop proportions (default)
#       --laptop                          Compact laptop sizing
#       --stock                           Build stock MacTahoe (no glass) - used for geometry diffing
#   -h, --help
#
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="${REPO_DIR}/src"

NAME="Fluid-Glass"
OUT_DIR="${REPO_DIR}/dist"
COLORS=(Dark Light)
STYLE="normal"
STOCK="false"
HD="true"

usage() { sed -n '3,18p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    -c|--color)
      case "${2:-}" in
        dark)  COLORS=(Dark) ;;
        light) COLORS=(Light) ;;
        all)   COLORS=(Dark Light) ;;
        *) echo "Unknown color '${2:-}'"; exit 1 ;;
      esac; shift 2 ;;
    -s|--style)
      case "${2:-}" in
        clear|normal|frosted) STYLE="$2" ;;
        *) echo "Unknown style '${2:-}'"; exit 1 ;;
      esac; shift 2 ;;
    -n|--name) NAME="$2"; shift 2 ;;
    -o|--out)  OUT_DIR="$2"; shift 2 ;;
    --mac27|--hd) HD="true"; shift ;;
    --laptop)     HD="false"; shift ;;
    --stock)      STOCK="true"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option '$1'"; usage; exit 1 ;;
  esac
done

command -v sassc >/dev/null || { echo "sassc is required (sudo dnf install sassc)"; exit 1; }

# ---------------------------------------------------------------------------
# Detect GNOME Shell version the same way MacTahoe does
# ---------------------------------------------------------------------------
SHELL_VERSION="$(gnome-shell --version 2>/dev/null | cut -d ' ' -f 3 | cut -d . -f 1 || true)"
SHELL_VERSION="${SHELL_VERSION:-48}"
if   (( SHELL_VERSION >= 48 )); then WIDGETS="48-0"
elif (( SHELL_VERSION >= 47 )); then WIDGETS="47-0"
else                                 WIDGETS="46-0"
fi

SASSC_OPT="-M -t expanded"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT
cp -r "${SRC_DIR}/sass" "${SRC_DIR}/main" "${TMP}/"

# ---------------------------------------------------------------------------
# MacTahoe option files (identical to what MacTahoe's installer generates)
# ---------------------------------------------------------------------------
cp "${TMP}/sass/_gtk-base.scss" "${TMP}/sass/_gtk-base-temp.scss"
cp "${TMP}/sass/_theme-options.scss" "${TMP}/sass/_theme-options-temp.scss"
cp "${TMP}/main/gnome-shell/_shell-base.scss" "${TMP}/main/gnome-shell/_shell-base-temp.scss"

if [[ "${HD}" == "true" ]]; then
  sed -i "/\$laptop/s/true/false/" "${TMP}/sass/_gtk-base-temp.scss"
else
  sed -i "/\$sidebar_size/s/240px/200px/" "${TMP}/sass/_theme-options-temp.scss"
fi
if (( SHELL_VERSION >= 47 )); then
  sed -i "/\$gnome_version/s/old/new/" "${TMP}/sass/_gtk-base-temp.scss"
  sed -i "/\$shell_version/s/old/new/" "${TMP}/sass/_theme-options-temp.scss"
fi
sed -i "/GNOME_SHELL/s/46/${SHELL_VERSION}/" "${TMP}/main/gnome-shell/_shell-base-temp.scss"
sed -i "/widgets/s/46-0/${WIDGETS}/"        "${TMP}/main/gnome-shell/_shell-base-temp.scss"

# Glass options
cat > "${TMP}/sass/glass/_options-temp.scss" <<EOF
// Generated by build.sh
\$glass_style: '${STYLE}';
EOF

# ---------------------------------------------------------------------------
# Entry files
# ---------------------------------------------------------------------------
write_entries() {
  local color="$1" variant="${1,,}"
  local glass_shell="" glass_gtk3="" glass_gtk4=""
  if [[ "${STOCK}" == "false" ]]; then
    glass_shell="@import '../../sass/glass/shell';"
    glass_gtk3="@import '../../sass/glass/gtk3';"
    glass_gtk4="@import '../../sass/glass/gtk4';"
  fi

  cat > "${TMP}/main/gnome-shell/build${color}.scss" <<EOF
\$variant: '${variant}';
@import 'shell-base-temp';
${glass_shell}
EOF

  cat > "${TMP}/main/gtk-3.0/build${color}.scss" <<EOF
\$variant: '${variant}';
@import '../../sass/variables';
@import '../../sass/colors';
@import '../../sass/gtk/drawing-3.0';
@import '../../sass/gtk/common-3.0';
@import '../../sass/gtk/apps-3.0';
@import '../../sass/gtk/colors-public';
@import '../../sass/gtk/colors-other';
${glass_gtk3}
EOF

  cat > "${TMP}/main/gtk-4.0/build${color}.scss" <<EOF
\$variant: '${variant}';
@import '../../sass/variables';
@import '../../sass/colors';
@import '../../sass/gtk/colors-libadwaita';
@import '../../sass/gtk/drawing-4.0';
@import '../../sass/gtk/common-4.0';
@import '../../sass/gtk/apps-4.0';
@import '../../sass/gtk/colors-public';
${glass_gtk4}
EOF
}

for c in Dark Light; do write_entries "$c"; done

# ---------------------------------------------------------------------------
# Compile + assemble
# ---------------------------------------------------------------------------
A="${SRC_DIR}/assets"
mkdir -p "${OUT_DIR}"

for color in "${COLORS[@]}"; do
  THEME="${NAME}-${color}"
  [[ "${STOCK}" == "true" ]] && THEME="MacTahoe-stock-${color}"
  T="${OUT_DIR}/${THEME}"
  rm -rf "${T}"
  mkdir -p "${T}/gnome-shell/assets" "${T}/gtk-3.0" "${T}/gtk-4.0"

  echo "==> ${THEME}: gnome-shell"
  sassc ${SASSC_OPT} "${TMP}/main/gnome-shell/build${color}.scss" "${T}/gnome-shell/gnome-shell.css"
  cp -r "${A}/gnome-shell/icons"                    "${T}/gnome-shell/"
  cp    "${SRC_DIR}/main/gnome-shell/pad-osd.css"   "${T}/gnome-shell/"
  cp -r "${A}/gnome-shell/common-assets/"*          "${T}/gnome-shell/assets/"
  cp -r "${A}/gnome-shell/assets-${color}/"*        "${T}/gnome-shell/assets/"
  cp -r "${A}/gnome-shell/theme/"*                  "${T}/gnome-shell/assets/"
  cp    "${A}/gnome-shell/activities/activities-apple.svg" "${T}/gnome-shell/assets/activities.svg"
  cp    "${A}/gnome-shell/activities/activities-apple.svg" "${T}/gnome-shell/assets/activities-white.svg"
  for f in no-events.svg process-working.svg no-notifications.svg; do
    mv -f "${T}/gnome-shell/assets/${f}" "${T}/gnome-shell/${f}"
  done

  echo "==> ${THEME}: gtk-3.0"
  sassc ${SASSC_OPT} "${TMP}/main/gtk-3.0/build${color}.scss" "${T}/gtk-3.0/gtk.css"
  sassc ${SASSC_OPT} "${TMP}/main/gtk-3.0/buildDark.scss"     "${T}/gtk-3.0/gtk-dark.css"

  echo "==> ${THEME}: gtk-4.0"
  sassc ${SASSC_OPT} "${TMP}/main/gtk-4.0/build${color}.scss" "${T}/gtk-4.0/gtk.css"
  sassc ${SASSC_OPT} "${TMP}/main/gtk-4.0/buildDark.scss"     "${T}/gtk-4.0/gtk-dark.css"
  # Light variant is also shipped so libadwaita installs can follow the system color scheme
  sassc ${SASSC_OPT} "${TMP}/main/gtk-4.0/buildLight.scss"    "${T}/gtk-4.0/gtk-light.css"

  for g in gtk-3.0 gtk-4.0; do
    cp -r "${A}/gtk/common-assets/assets"                 "${T}/${g}/"
    cp -r "${A}/gtk/scalable"                             "${T}/${g}/assets/"
    cp -r "${A}/gtk/windows-assets/titlebutton"           "${T}/${g}/windows-assets"
    cp    "${A}/gtk/thumbnails/thumbnail-${color}.png"    "${T}/${g}/thumbnail.png" 2>/dev/null || true
  done

  cat > "${T}/index.theme" <<EOF
[Desktop Entry]
Type=X-GNOME-Metatheme
Name=Fluid Glass for Linux (${color})
Comment=Fluid Glass for Linux with macOS 27" geometry (${STYLE})
Encoding=UTF-8

[X-GNOME-Metatheme]
GtkTheme=${THEME}
MetacityTheme=${THEME}
IconTheme=Adwaita
CursorTheme=Adwaita
ButtonLayout=close,minimize,maximize:menu
EOF
done

echo "==> Done. Output in ${OUT_DIR} (shell ${SHELL_VERSION}, widgets ${WIDGETS}, style ${STYLE}${HD:+, hd=${HD}})"
